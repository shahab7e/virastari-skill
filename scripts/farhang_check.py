def apply_fix(text, log):
    for rid, pat, rep, ref in FIX:
        def _r(m, rid=rid, rep=rep):
            new = rep(m)
            if new != m.group(0): log.append((rid, m.group(0), new))
            return new
        text = re.sub(pat, _r, text)
    return text

def scan(text):
    out = []
    for ln, line in enumerate(text.split("\n"), 1):
        for rid, pat, hint, ref in [(f[0], f[1], "اصلاح مکانیکی (--fix)", f[3]) for f in FIX] + CLUES:
            for m in re.finditer(pat, line):
                out.append((ln, rid, m.group(0), line[max(0, m.start()-20):m.end()+20], hint, ref))
        for bad, good in PREF.items():
            for m in re.finditer(B + re.escape(bad) + E, line):
                out.append((ln, "chandemlayi", m.group(0), line[max(0, m.start()-20):m.end()+20], f"← {good} (املای مرجّح فرهنگستان)", "ص ۷۳–۸۵"))
    if "ّ" in text:
        out.append((0, "tashdid", f"{text.count(chr(0x651))} تشدید", "", "تشدید فقط برای رفع ابهام لازم است؛ در متون آموزشی نوآموزان و اسناد رسمی دولتی همه‌جا لازم — یکدست کن", "ص ۵۶–۵۷"))
    return out

def load(path):
    if path.lower().endswith(".docx"):
        import docx; d = docx.Document(path)
        return d, list(d.paragraphs) + [p for t in d.tables for r in t.rows for c in r.cells for p in c.paragraphs]
    return None, open(path, encoding="utf-8").read()

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("path"); ap.add_argument("--fix", action="store_true")
    ap.add_argument("-o", "--out"); ap.add_argument("--log"); a = ap.parse_args()
    log = []; d, src = load(a.path)
    if d is not None:
        if a.fix:
            for p in src:
                new = apply_fix(p.text, log)
                if new != p.text and p.runs:
                    p.runs[0].text = new
                    for r in p.runs[1:]: r.text = ""
            d.save(a.out)
        text = "\n".join(p.text for p in src)
    else:
        text = apply_fix(src, log) if a.fix else src
        if a.fix: open(a.out, "w", encoding="utf-8").write(text)
    if a.log:
        with open(a.log, "w", encoding="utf-8") as f:
            f.write("rule\tbefore\tafter\n"); f.writelines("\t".join(x.replace(ZW, "<ZWNJ>") for x in r) + "\n" for r in log)
    if a.fix: print("اصلاحات فرهنگستان:", ", ".join(f"{k}={v}" for k, v in Counter(r[0] for r in log).most_common()) or "هیچ")
    fs = scan(text)
    print("| سطر | قاعده | یافته | بافت | راهنما | مرجع فرهنگستان |\n|---|---|---|---|---|---|")
    for ln, rid, mt, ctx, hint, ref in fs:
        print(f"| {ln} | {rid} | {mt} | {ctx.replace('|', '¦')} | {hint} | {ref} |")
    if not fs: print("| – | – | سرنخی نیافت | | | |")

if __name__ == "__main__":
    main()
